/* main.cpp — STM32F407 sine-inference LED/UART firmware
 *
 * Every ~100ms: steps x through 0..359 (degrees), runs the exported sine
 * model on angle = x in radians, drives the green LED's PWM brightness
 * from the model's output y (via TIM4_CH1/PD12), and prints
 * "x=... y=... angle=..." over USART2 every 10 steps.
 */

#include <cstdint>

#include "stm32f407.h"

#include "executorch/runtime/executor/program.h"
#include "executorch/runtime/executor/method.h"
#include "executorch/runtime/core/exec_aten/exec_aten.h"
#include "executorch/runtime/core/portable_type/tensor_impl.h"
#include "executorch/runtime/core/hierarchical_allocator.h"
#include "executorch/runtime/platform/runtime.h"
#include "executorch/extension/data_loader/buffer_data_loader.h"

/*
 * Generated by CMakeLists.txt using:
 *   xxd -i sine_model.pte
 * run from the models/ directory, so the generated array is named
 * sine_model_pte / sine_model_pte_len. Lands in ${CMAKE_BINARY_DIR}, which
 * is already on the include path.
 */
#include "sine_model_pte.h"

using namespace executorch::runtime;
using namespace executorch::extension;
using namespace executorch::runtime::etensor;

/* ── Clock / timing ─────────────────────────────────────────────────────
 * No PLL is configured anywhere in startup_stm32f407.s, so still on
 * the reset-default HSI 16 MHz with no APB prescaling.
 * ────────────────────────────────────────────────────────────────────── */
#define SYSCLK_HZ       16000000UL
#define SYSTICK_1MS     (SYSCLK_HZ / 1000U - 1U)

/* BRR for 115200 baud, 16x oversampling (OVER8=0), APB1 = 16 MHz --
 * derivation in first_embedded/main.c. */
#define USART2_BRR_VAL  ((8U << 4) | 11U)

#define UART_TX_PIN     2U      /* PA2 = USART2 TX, AF7 */
#define UART_AF         7U

#define LED_PIN         12U
#define LED_TIM_AF      2U      /* TIM4's alternate function number */

#define PWM_PSC         15U     /* 16 MHz / (15+1) = 1 MHz timer clock    */
#define PWM_PERIOD      1000U   /* 1 MHz / 1000 = 1 kHz PWM, duty 0..1000 */

#define STEP_PERIOD_MS  100U    /* one inference step every ~100 ms       */

static constexpr float kPi = 3.14159265358979323846f;

/* ── SysTick — drives the ~100ms step cadence ──────────────────────────── */
static volatile uint32_t g_ticks = 0;

extern "C" void SysTick_Handler(void) {
    g_ticks++;
}

static void systick_init(void) {
    SYSTICK->LOAD = SYSTICK_1MS;
    SYSTICK->VAL  = 0;
    SYSTICK->CTRL = SYSTICK_CTRL_CLKSOURCE
                  | SYSTICK_CTRL_TICKINT
                  | SYSTICK_CTRL_ENABLE;
}

/* ── UART2 — PA2 TX only, we never read ────────────────────────────────── */
static void uart_init(void) {
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN;
    RCC->APB1ENR |= RCC_APB1ENR_USART2EN;
    (void)RCC->APB1ENR;    /* read-back to ensure clock is on before access */

    GPIOA->MODER   &= ~(0x3U << (UART_TX_PIN * 2U));
    GPIOA->MODER   |=  (GPIO_MODER_AF << (UART_TX_PIN * 2U));
    GPIOA->OTYPER  &= ~(1U << UART_TX_PIN);
    GPIOA->OSPEEDR |=  (0x2U << (UART_TX_PIN * 2U));
    GPIOA->AFR[0]  &= ~(0xFU << (UART_TX_PIN * 4U));
    GPIOA->AFR[0]  |=  (UART_AF << (UART_TX_PIN * 4U));

    USART2->CR1 = 0;
    USART2->BRR = USART2_BRR_VAL;
    USART2->CR2 = 0;    /* 1 stop bit */
    USART2->CR3 = 0;    /* no flow control */
    USART2->CR1 = USART_CR1_UE | USART_CR1_TE;
}

static void uart_putchar(char c) {
    while (!(USART2->SR & USART_SR_TXE)) {}
    USART2->DR = (uint8_t)c;
}

static void uart_puts(const char *s) {
    while (*s) uart_putchar(*s++);
    while (!(USART2->SR & USART_SR_TC)) {}   /* wait for last byte to shift out */
}

/* ── PWM on TIM4_CH1 / PD12 (green LED) ────────────────────────────────────
 * PD12 needs AF2 for TIM4 -- a different alternate function than UART's
 * AF7 on PA2, even though both are configured as GPIO_MODER_AF.
 * ────────────────────────────────────────────────────────────────────── */
static void pwm_init(void) {
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIODEN;
    RCC->APB1ENR |= RCC_APB1ENR_TIM4EN;
    (void)RCC->APB1ENR;

    GPIOD->MODER   &= ~(0x3U << (LED_PIN * 2U));
    GPIOD->MODER   |=  (GPIO_MODER_AF << (LED_PIN * 2U));
    GPIOD->OTYPER  &= ~(1U << LED_PIN);
    GPIOD->OSPEEDR &= ~(0x3U << (LED_PIN * 2U));
    GPIOD->PUPDR   &= ~(0x3U << (LED_PIN * 2U));
    /* LED_PIN = 12 falls in AFR[1] (covers pins 8-15), at nibble (12-8). */
    GPIOD->AFR[1]  &= ~(0xFU << ((LED_PIN - 8U) * 4U));
    GPIOD->AFR[1]  |=  (LED_TIM_AF << ((LED_PIN - 8U) * 4U));

    TIM4->PSC   = PWM_PSC;
    TIM4->ARR   = PWM_PERIOD - 1U;
    TIM4->CCR1  = 0;
    TIM4->CCMR1 = TIM_CCMR1_OC1M_PWM1 | TIM_CCMR1_OC1PE;
    TIM4->CCER |= TIM_CCER_CC1E;
    TIM4->CR1  |= TIM_CR1_ARPE;
    TIM4->EGR   = TIM_EGR_UG;    /* force shadow registers to load now */
    TIM4->CR1  |= TIM_CR1_CEN;
}

/* y is the model's sin(angle) output, in [-1, 1] -- map linearly to a
 * [0, 100%] duty cycle: y=-1 -> 0%, y=0 -> 50%, y=+1 -> 100%. */
static inline void pwm_set_duty(float y) {
    float ratio = (y + 1.0f) * 0.5f;
    if (ratio < 0.0f) ratio = 0.0f;
    if (ratio > 1.0f) ratio = 1.0f;
    TIM4->CCR1 = (uint32_t)(ratio * (float)PWM_PERIOD + 0.5f);
}

/* ── Minimal string-building helpers (no snprintf -- keeps things simple
 * and avoids pulling in more of newlib-nano's formatting code) ─────────── */
static char* append_str(char *p, const char *s) {
    while (*s) *p++ = *s++;
    return p;
}

static char* append_uint(char *p, uint32_t v) {
    char tmp[10];
    int n = 0;
    if (v == 0U) {
        tmp[n++] = '0';
    } else {
        while (v > 0U) {
            tmp[n++] = (char)('0' + (v % 10U));
            v /= 10U;
        }
    }
    while (n > 0) *p++ = tmp[--n];
    return p;
}

static char* append_float(char *p, float v, int decimals) {
    if (v < 0.0f) {
        *p++ = '-';
        v = -v;
    }
    uint32_t scale = 1U;
    for (int i = 0; i < decimals; i++) scale *= 10U;

    uint32_t scaled    = (uint32_t)(v * (float)scale + 0.5f);
    uint32_t int_part  = scaled / scale;
    uint32_t frac_part = scaled % scale;

    p = append_uint(p, int_part);
    *p++ = '.';

    uint32_t divisor = scale / 10U;
    while (divisor > 0U) {
        *p++ = (char)('0' + (frac_part / divisor) % 10U);
        divisor /= 10U;
    }
    return p;
}

// CCM RAM size is 64KB on STM32F407. We split it between method metadata and planned tensors.
// Adjust sizes as needed for larger models or more intermediate tensors.

/*
 * Method allocator pool — holds method metadata, operator state, etc.
 * Placed in .ccmram (zero-initialized).
 */
__attribute__((section(".ccmram")))
static uint8_t method_pool[24 * 1024];

/*
 * Planned memory pool — holds intermediate tensors during execution.
 * ExecuTorch memory-plans tensor lifetimes at export time; this pool
 * provides the backing storage for those planned allocations.
 */
__attribute__((section(".ccmram")))
static uint8_t planned_pool[38 * 1024];

/*
 * Input data — static so it has a stable address throughout execution.
 * Stack-allocated arrays can be corrupted if the call stack grows deep
 * during method loading/execution.
 *
 * Shape [1, 1]: one scalar angle in, one scalar sin(angle) out -- matches
 * train_and_export.py's example_input = torch.randn(1, 1).
 */
static float                    input_data[1] = {0.0f};
static TensorImpl::SizesType    sizes[2]      = {1, 1};
static TensorImpl::DimOrderType dim_order[2]  = {0, 1};
static TensorImpl::StridesType  strides[2]    = {1, 1};

int main() {
    systick_init();
    uart_init();
    pwm_init();

    // Initialize ExecuTorch runtime (sets up PAL, logging infrastructure)
    runtime_init();

    // Load program from flash-resident byte array.
    // BufferDataLoader takes a pointer + size and serves any byte offset
    // into the buffer — used for both the FlatBuffer program data and
    // the constant segment (model weights/constants stored after the
    // FlatBuffer in the .pte file).
    BufferDataLoader loader(sine_model_pte, sine_model_pte_len);

    Result<Program> program_result = Program::load(
        &loader,
        Program::Verification::Minimal);
    if (!program_result.ok()) {
        volatile uint32_t err = (uint32_t)program_result.error();
        (void)err;
        while (1); // inspect err in debugger
    }
    Program program = std::move(program_result.get());

    // Set up memory for method loading.
    // MemoryAllocator: bump allocator for method metadata.
    // HierarchicalAllocator: provides memory arenas for planned tensors.
    // MemoryManager: combines both and is passed to load_method.
    MemoryAllocator method_allocator(sizeof(method_pool), method_pool);
    Span<uint8_t> planned_span(planned_pool, sizeof(planned_pool));
    HierarchicalAllocator planned_allocator({&planned_span, 1});
    MemoryManager memory_manager(&method_allocator, &planned_allocator);

    Result<Method> method_result = program.load_method("forward", &memory_manager);
    if (!method_result.ok()) {
        volatile uint32_t err = (uint32_t)method_result.error();
        (void)err;
        while (1); // inspect err in debugger: 0x14 = OperatorMissing
    }
    Method method = std::move(method_result.get());

    // Construct input tensor.
    // TensorImpl takes: scalar type, number of dimensions, sizes array,
    // data pointer, dim_order array, strides array.
    // All arrays must be static (stable address) — see declarations above.
    TensorImpl input_impl(
        ScalarType::Float,
        /*dim=*/2,
        sizes,
        input_data,
        dim_order,
        strides
    );
    Tensor input_tensor(&input_impl);

    uart_puts("\r\n=== sine inference LED/UART demo ===\r\n");

    uint32_t x = 0;                 /* degrees, wraps 0..359 */
    uint32_t next_step = g_ticks;   /* run the first step immediately */

    while (1) {
        /* Wait for the next ~100ms tick boundary. Advancing next_step by a
         * fixed increment (rather than resetting it from `now`) avoids
         * accumulating drift across steps. */
        while ((int32_t)(g_ticks - next_step) < 0) {}
        next_step += STEP_PERIOD_MS;

        float angle = (float)x * (kPi / 180.0f);
        input_data[0] = angle;

        Error set_err = method.set_input(EValue(input_tensor), 0);
        if (set_err != Error::Ok) {
            while (1);
        }

        // Run inference
        Error exec_err = method.execute();
        if (exec_err != Error::Ok) {
            while (1);
        }

        EValue output = method.get_output(0);
        Tensor out_tensor = output.toTensor();
        float y = out_tensor.const_data_ptr<float>()[0];

        pwm_set_duty(y);

        if (x % 10U == 0U) {
            char msg[64];
            char *p = msg;
            p = append_str(p, "x=");
            p = append_uint(p, x);
            p = append_str(p, " y=");
            p = append_float(p, y, 4);
            p = append_str(p, " angle=");
            p = append_float(p, angle, 4);
            p = append_str(p, "\r\n");
            *p = '\0';
            uart_puts(msg);
        }

        x = (x + 1U) % 360U;
    }
}
